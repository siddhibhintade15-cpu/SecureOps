def save_synthetic_csv_to_disk(filepath: Path) -> Path:
    """Persist the synthetic dataset to disk for user inspection and CLI use."""
    filepath.parent.mkdir(parents=True, exist_ok=True)
    df = load_synthetic_sample_dataframe()
    df.to_csv(filepath, index=False)
    return filepath


def export_remediation_plan_csv(plan_df: pd.DataFrame) -> bytes:
    """Export the remediation plan with calculations and approval status to CSV bytes."""
    export_cols = [
        "cve_id",
        "vulnerability_title",
        "asset_name",
        "asset_criticality",
        "cvss_score",
        "epss_score",
        "cisa_kev",
        "exploit_evidence",
        "internet_exposed",
        "risk_score",
        "priority",
        "remediation_category",
        "plan_status",
        "approval_status",
        "deferral_reason",
        "remediation_effort_hours",
        "maintenance_window",
        "remediation_cost_est",
        "risk_roi",
    ]
    available_cols = [col for col in export_cols if col in plan_df.columns]
    return plan_df[available_cols].to_csv(index=False).encode("utf-8")


def export_audit_manifest_json(summary: Any, plan_df: pd.DataFrame) -> str:
    """Generate structured JSON audit manifest of the remediation plan."""
    manifest = {
        "generator": "SecureOps AI: Autonomous Vulnerability Remediation Planner",
        "timestamp_utc": datetime.now(timezone.utc).isoformat(),
        "plan_summary": {
            "total_cves": summary.total_cves,
            "planned_count": summary.planned_cves_count,
            "deferred_count": summary.deferred_cves_count,
            "allocated_hours": summary.allocated_hours,
            "capacity_limit_hours": summary.capacity_hours_limit,
            "capacity_utilization_pct": summary.hours_utilization_pct,
            "estimated_cost": summary.allocated_cost,
            "baseline_mean_risk": summary.baseline_mean_risk,
            "residual_mean_risk": summary.projected_mean_risk,
            "projected_risk_reduction_pct": summary.risk_reduction_pct,
            "verified_count": getattr(summary, "verified_cves_count", 0),
            "verified_risk_reduction_pct": getattr(summary, "verified_risk_reduction_pct", 0.0),
        },
        "planned_vulnerabilities": plan_df[plan_df["plan_status"] == "Planned"][
            ["cve_id", "asset_name", "risk_score", "priority", "remediation_category", "approval_status"]
        ].to_dict(orient="records"),
        "deferred_vulnerabilities": plan_df[plan_df["plan_status"] != "Planned"][
            ["cve_id", "asset_name", "risk_score", "deferral_reason"]
        ].to_dict(orient="records"),
        "human_governance_notice": (
            "Mandatory Human Approval policy in effect. No automatic live patching executed."
        ),
    }
    return json.dumps(manifest, indent=2)
